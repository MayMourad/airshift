import { formatTime, type Dataset, type EvidenceResult } from './data'
import { BUDGETS, STATUS_META, statusOf, type BudgetTier } from './model'

const esc = (s: string) => s.replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]!)
const f = (n: number, d = 1) => (Number.isFinite(n) ? n.toFixed(d) : '—')
const pct = (n: number) => (Number.isFinite(n) ? `${n > 0 ? '+' : ''}${(n * 100).toFixed(0)}%` : '—')

export function buildReportHtml(ds: Dataset, ev: EvidenceResult, roomLabel: string, budget: BudgetTier): string {
  const sim = ds.source === 'synthetic'
  const b = BUDGETS[budget]
  const row = (label: string, a: string, c: string, d = '') => `<tr><th scope="row">${esc(label)}</th><td>${a}</td><td>${c}</td><td>${d}</td></tr>`
  const s = ev.before.summary
  const t = ev.after.summary
  const win = (p: typeof ev.before) => `${esc(formatTime(ds, p.from, false))} → ${esc(formatTime(ds, p.to - 1, false))}`
  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>AIRSHIFT ${sim ? 'SAMPLE ' : ''}Evidence Report — ${esc(roomLabel)}</title>
<style>
body{font:15px/1.55 Inter,system-ui,sans-serif;color:#0b1d29;max-width:820px;margin:32px auto;padding:0 20px}
h1{font:600 28px 'Space Grotesk',system-ui;margin:0 0 4px}h2{font:600 18px 'Space Grotesk',system-ui;margin:28px 0 8px;border-bottom:2px solid #16D6BC;padding-bottom:4px}
.banner{background:#fff4dc;border:2px solid #F5BD67;border-radius:10px;padding:12px 16px;font-weight:600;margin:16px 0}
table{border-collapse:collapse;width:100%;margin:8px 0;font-variant-numeric:tabular-nums}th,td{border:1px solid #cfdde3;padding:6px 10px;text-align:left}thead th{background:#eaf7f6}
.mono{font-family:'IBM Plex Mono',ui-monospace,monospace}.small{font-size:12.5px;color:#4a6472}li{margin:4px 0}
</style></head><body>
<p class="small mono">AIRSHIFT · Young Planet Leaders Changemaker Academy 2026 · generated ${esc(new Date().toISOString().slice(0, 10))}</p>
<h1>Before-and-after PM2.5 evidence report</h1>
<p>Room: <strong>${esc(roomLabel)}</strong> · Data source: ${esc(ds.label)}</p>
${sim ? '<div class="banner">SIMULATED SAMPLE REPORT. The readings below are synthetic demonstration data generated by the AIRSHIFT prototype. They are not measurements of any real room and do not show that any intervention works.</div>' : '<div class="banner" style="background:#eaf7f6;border-color:#16D6BC">Report built from a user-imported CSV. Values have not been independently verified by AIRSHIFT.</div>'}
<h2>1. Measurement windows</h2>
<table><thead><tr><th></th><th>Before</th><th>After</th><th></th></tr></thead><tbody>
${row('Window', win(ev.before), win(ev.after))}
${row('School days with usable data', String(ev.before.schoolDays), String(ev.after.schoolDays))}
${row('School-hour readings (Mon–Fri 07:00–15:00)', String(s.n), String(t.n))}
${row('Completeness', `${f(ev.before.completeness * 100, 0)}%`, `${f(ev.after.completeness * 100, 0)}%`)}
</tbody></table>
<p class="small">The intervention day itself is excluded as a transition day.</p>
<h2>2. PM2.5 summary (µg/m³, school hours)</h2>
<table><thead><tr><th></th><th>Before</th><th>After</th><th>Change</th></tr></thead><tbody>
${row('Mean', f(s.mean), f(t.mean), pct(ev.pct))}
${row('Median', f(s.median), f(t.median), pct((t.median - s.median) / s.median))}
${row('Standard deviation', f(s.sd), f(t.sd))}
${row('Interquartile range', `${f(s.q1)}–${f(s.q3)}`, `${f(t.q1)}–${f(t.q3)}`)}
${row('95th percentile', f(s.p95), f(t.p95), pct((t.p95 - s.p95) / s.p95))}
${row('Minimum – maximum', `${f(s.min)} – ${f(s.max)}`, `${f(t.min)} – ${f(t.max)}`)}
</tbody></table>
<p>Raw change in mean: <strong>${pct(ev.pct)}</strong> (95% interval from resampling daily means: ${pct(ev.pctCi[0])} to ${pct(ev.pctCi[1])}). The interval reflects day-to-day variability only. It does not include sensor bias or confounding.</p>
<p>Status of the "after" mean against WHO reference bands: ${esc(STATUS_META[statusOf(t.mean)].short)}.</p>
<h2>3. Conditions</h2>
<table><thead><tr><th></th><th>Before</th><th>After</th><th>Change</th></tr></thead><tbody>
${row('Outdoor PM2.5 mean (µg/m³)', f(ev.before.outdoorMean), f(ev.after.outdoorMean), pct((ev.after.outdoorMean - ev.before.outdoorMean) / ev.before.outdoorMean))}
${row('Indoor ÷ outdoor ratio', f(ev.before.ioRatio, 2), f(ev.after.ioRatio, 2), pct(ev.ratioPct))}
${row('Relative humidity mean (%)', f(ev.before.rhMean, 0), f(ev.after.rhMean, 0))}
${row('CO2 mean (ppm) — separate ventilation metric', f(ev.before.co2Mean, 0), f(ev.after.co2Mean, 0))}
</tbody></table>
${ev.comparison ? `<p>Comparison room (${esc(ev.comparison.room)}, no intervention): indoor ÷ outdoor ratio changed ${pct(ev.comparison.ratioPct)}. Treated-room ratio change relative to the comparison room: <strong>${pct(ev.comparison.adjustedVsComparisonPct)}</strong>.</p>` : ''}
<h2>4. Implementation cost (preliminary planning figures, not supplier quotations)</h2>
<p>Budget scenario: <strong>$${b.total}</strong> — ${esc(b.scope)}</p>
<ul>${b.lines.map((l) => `<li>${esc(l.label)}: $${l.amount}</li>`).join('')}</ul>
<h2>5. Data-quality warnings and limitations</h2>
<ul>${ev.warnings.map((w) => `<li><strong>${esc(w.title)}.</strong> ${esc(w.detail)}</li>`).join('')}</ul>
<h2>6. How to read this report</h2>
<ul>
<li>Observed values and estimates are kept separate. Nothing here is a prediction.</li>
<li>Low-cost optical sensors carry unknown absolute bias; humidity and dust type affect them.</li>
<li>Changes may reflect outdoor conditions, humidity, occupancy, ventilation or cleaning routines, not only the intervention.</li>
<li>A lower PM2.5 reading does not by itself show better health. AIRSHIFT makes no medical or health-risk claims.</li>
<li>No student-identifiable information is collected or included.</li>
</ul>
<h2>Sources</h2>
<ul class="small">
<li>World Health Organization, Air pollution — https://www.who.int/health-topics/air-pollution</li>
<li>US CDC/NIOSH, Ventilation in Schools and Childcare Programs — https://www.cdc.gov/niosh/ventilation/guidelines/</li>
<li>US EPA, Guide to Air Cleaners in the Home — https://www.epa.gov/indoor-air-quality-iaq/guide-air-cleaners-home</li>
</ul>
</body></html>`
}
